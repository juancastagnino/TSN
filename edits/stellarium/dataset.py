"""Prepare a Stellarium script, validate its output and compare with TYCHOS.

Stellarium is retained as its own source, never disguised as Horizons/ICRF.
"""
import argparse
import csv
import hashlib
import json
import math
import sys
import uuid
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT/'edits/scripts'))
from download_jpl import expected_dates
from compare_ephemerides import read_tychos, angular_separation_deg, wrap_deg, rms


def prepare(args):
    config = json.loads((ROOT/'edits/scripts/analysis_config.json').read_text(encoding='utf-8'))
    registry = json.loads((ROOT/'edits/scripts/bodies.json').read_text(encoding='utf-8'))
    bodies = config['bodies']
    if not bodies or len(set(bodies)) != len(bodies) or set(bodies)-set(registry):
        raise ValueError('Invalid body selection')
    start, stop, step = args.start or config['start'], args.stop or config['stop'], config['step']
    dates = [d.isoformat() for d in expected_dates(start, stop, step)]
    profile = args.profile.resolve()
    (profile/'scripts').mkdir(parents=True, exist_ok=True)
    manifest = {'source': 'Stellarium', 'run_id': uuid.uuid4().hex, 'bodies': bodies, 'dates': dates,
                'frame': 'Stellarium J2000 and equinox-of-date',
                'observer': 'Earth geocenter', 'light_travel_time': False,
                'atmosphere': False, 'tychos': config['tychos']}
    script = '''// Generated by edits/stellarium/dataset.py; isolated export profile.
core.resetOutput();
core.setTimeRate(0);
core.setObserverLocation(0, 0, 0, 0, "TSN", "Earth");
core.setPlanetocentricCalculations(true);
core.setStelProperty("StelCore.flagUseAberration", false);
LandscapeMgr.setFlagAtmosphere(false);
SolarSystem.setFlagLightTravelTime(false);
var dates = DATES;
var bodies = BODIES;
function emit(x) { core.output(JSON.stringify(x)); }
emit({kind:"metadata", source:"Stellarium", run_id:RUN_ID, planetocentric:core.isPlanetocentricCalculations(),
      light_travel_time:SolarSystem.getFlagLightTravelTime(),
      aberration:core.getStelProperty("StelCore.flagUseAberration"),
      delta_t_algorithm:core.getDeltaTAlgorithm(), location:core.getObserverLocationInfo()});
for (var i=0; i<dates.length; i++) {
    core.setDate(dates[i], "utc");
    core.wait(WAIT);
    for (var j=0; j<bodies.length; j++) {
        var name = bodies[j].charAt(0).toUpperCase()+bodies[j].slice(1);
        var info = core.getObjectInfo(name);
        emit({kind:"position", date:dates[i], actual_date:core.getDate("utc"), body:bodies[j],
              ra:((info.raJ2000%360)+360)%360, dec:info.decJ2000,
              ra_date:((info.ra%360)+360)%360, dec_date:info.dec,
              delta_t_seconds:core.getDeltaTsec()});
    }
}
emit({kind:"complete", count:dates.length*bodies.length});
core.saveOutputAs("stellarium_export.jsonl");
core.quitStellarium();
'''.replace('DATES', json.dumps(dates)).replace('BODIES', json.dumps(bodies)).replace('WAIT', str(args.wait)).replace('RUN_ID', json.dumps(manifest['run_id']))
    (profile/'scripts/export.ssc').write_text(script, encoding='utf-8')
    (profile/'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Prepared {len(dates)*len(bodies)} positions in {profile}')


def read_export(path, manifest):
    entries = [json.loads(line) for line in path.read_text(encoding='utf-8-sig').splitlines() if line.strip()]
    if not entries or entries[0].get('kind') != 'metadata' or entries[-1].get('kind') != 'complete':
        raise ValueError('Incomplete Stellarium export')
    meta = entries[0]
    if meta.get('run_id') != manifest['run_id']:
        raise ValueError('Export belongs to an earlier run; rerun the generated script')
    if (meta.get('source') != 'Stellarium' or meta.get('planetocentric') is not True
            or meta.get('light_travel_time') is not False or meta.get('aberration') is not False):
        raise ValueError('Unexpected observer/correction settings')
    expected = {(d, b) for d in manifest['dates'] for b in manifest['bodies']}
    rows = {}
    for row in entries[1:-1]:
        key = (row['date'], row['body'])
        if row.get('kind') != 'position' or key in rows or key not in expected:
            raise ValueError('Duplicate or unexpected position')
        actual = datetime.fromisoformat(row['actual_date'].removesuffix('Z'))
        if abs((actual-datetime.fromisoformat(row['date'])).total_seconds()) > 1:
            raise ValueError('Simulation date does not match requested date')
        for field in ('ra', 'dec', 'ra_date', 'dec_date', 'delta_t_seconds'):
            if not isinstance(row.get(field), (int, float)) or not math.isfinite(row[field]):
                raise ValueError(f'Missing/invalid {field}: {key}')
        if not (0 <= row['ra'] <= 360 and 0 <= row['ra_date'] <= 360 and
                abs(row['dec']) <= 90 and abs(row['dec_date']) <= 90):
            raise ValueError('Invalid coordinate range')
        rows[key] = row
    if set(rows) != expected or entries[-1]['count'] != len(expected):
        raise ValueError('Incomplete timestamp/body grid')
    for body in manifest['bodies']:
        positions = [(rows[(d, body)]['ra'], rows[(d, body)]['dec']) for d in manifest['dates']]
        if any(a == b for a, b in zip(positions, positions[1:])):
            raise ValueError('Repeated positions: Stellarium may not have updated its scene')
    return meta, rows


def collect(args):
    profile = args.profile.resolve()
    manifest = json.loads((profile/'manifest.json').read_text(encoding='utf-8'))
    raw = profile/'stellarium_export.jsonl'
    meta, rows = read_export(raw, manifest)
    ty_path = ROOT/manifest['tychos']
    comparisons = []
    summary = {}
    for body in manifest['bodies']:
        ty = read_tychos(ty_path, strict=True, body=body)
        metrics = {'j2000': [], 'of_date': []}
        for date in manifest['dates']:
            dt = datetime.fromisoformat(date)
            if dt not in ty:
                raise ValueError(f'TYCHOS missing {body} {date}')
            row, target = rows[(date, body)], ty[dt]
            for frame, ra, dec in [('j2000', row['ra'], row['dec']), ('of_date', row['ra_date'], row['dec_date'])]:
                sep = angular_separation_deg(target['ra'], target['dec'], ra, dec)
                metrics[frame].append(sep)
                comparisons.append([date, body, frame, target['ra'], target['dec'], ra, dec,
                                    wrap_deg(target['ra']-ra), target['dec']-dec, sep])
        summary[body] = {frame: {'count': len(values), 'separation_rms_deg': rms(values)} for frame, values in metrics.items()}
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    # Publish only after all data and TYCHOS timestamps have passed validation.
    (output/'stellarium_ephemerides.jsonl').write_bytes(raw.read_bytes())
    provenance = {'manifest': manifest, 'settings': meta, 'summary': summary,
                  'sha256': {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in
                             (raw, ty_path, profile/'scripts/export.ssc')},
                  'warning': 'Frame compatibility is not established by a lower RMS. Not Horizons astrometric data.'}
    for name in ('log.txt', 'config.ini'):
        if (profile/name).exists():
            (output/('stellarium_'+name)).write_bytes((profile/name).read_bytes())
    (output/'report.json').write_text(json.dumps(provenance, indent=2), encoding='utf-8')
    with (output/'comparison.csv').open('w', newline='', encoding='utf-8') as stream:
        writer = csv.writer(stream)
        writer.writerow(['date_utc', 'body', 'stellarium_frame', 'ty_ra_deg', 'ty_dec_deg',
                         'stellarium_ra_deg', 'stellarium_dec_deg', 'dra_deg', 'ddec_deg', 'separation_deg'])
        writer.writerows(comparisons)
    lines = ['# TYCHOS versus Stellarium', '', 'Angular separation RMS (degrees).', '',
             '| Body | J2000 | Of date |', '|---|---:|---:|']
    for body, values in summary.items():
        lines.append(f"| {body} | {values['j2000']['separation_rms_deg']:.6f} | {values['of_date']['separation_rms_deg']:.6f} |")
    lines += ['', provenance['warning']]
    (output/'report.md').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'collect'])
    parser.add_argument('--profile', type=Path, default=HERE/'profile')
    parser.add_argument('--output', type=Path, default=ROOT/'edits/data/stellarium')
    parser.add_argument('--start')
    parser.add_argument('--stop')
    parser.add_argument('--wait', type=float, default=0.2, help='Real seconds per date to let the scene update')
    args = parser.parse_args()
    if not math.isfinite(args.wait) or args.wait <= 0:
        parser.error('--wait must be positive')
    try:
        (prepare if args.action == 'prepare' else collect)(args)
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, str(error)+'\n')
